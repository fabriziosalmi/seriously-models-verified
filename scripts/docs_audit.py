"""Markdown rendering of the forensic audit (DISCREPANCY_AUDIT.md) from data/inconsistencies_catalog.json.

Every number printed here comes from the catalog, which is built from the evidence ledger; every case row links
each number to the verbatim quote and the physical PDF page it was verified on.
"""

import json

import evidence

ROOT = evidence.ROOT


def pts(v) -> str:
    return f"{v:.1f}" if round(v, 1) == v else f"{v:.2f}"


def quote_of(claim) -> str:
    q = claim["quotes"][0]
    text = q["text"] if isinstance(q, dict) else q
    return evidence.normalise(text).replace("|", "/").replace("`", "")


def source_ref(claim, sources) -> str:
    s = sources[claim["source"]]
    loc = f"PDF p.{claim['page']}" if s["ext"] == "pdf" else s["ext"].upper()
    return f"[`{claim['source']}`]({s['url']}), {loc}"


def evidence_line(cid, claims, sources) -> str:
    c = claims[cid]
    val = f"**{pts(c['value'])}**" if c.get("value") is not None else "(negative evidence)"
    return (f"- {val} {c['model']}, {c['benchmark']}, {c.get('protocol', '')}. Reported by {c['reported_by']}. "
            f"{source_ref(c, sources)}: \"{quote_of(c)}\" (claim `{cid}`)")


def build_audit_markdown(catalog, claims, sources) -> str:
    s = catalog["summary"]
    L = [
        "# Discrepancy Audit: Verified Cross-Source Benchmark Discrepancies (2021-2026)",
        "",
        "This document is generated by `scripts/build_docs_and_pdf.py` from `data/inconsistencies_catalog.json`, which "
        "`scripts/build_forensic_analysis.py` builds from the evidence ledger `data/claims.json`. Do not edit it by hand.",
        "",
        "## 1. Method",
        "",
        "1. Every source document is pinned: arXiv papers by explicit version, vendor pages and system cards by a "
        "timestamped Wayback Machine capture, GitHub files by commit, HELM results by release. The SHA-256 of each file "
        "is recorded in `data/downloaded_sources_manifest.json`; `scripts/download_sources.py` refuses to re-pin a "
        "source whose bytes changed.",
        "2. Every number is a claim in `data/claims.json`: source, physical PDF page, one or more verbatim quotes, the "
        "value, and for table cells the column index. `scripts/evidence.py` checks mechanically that each quote occurs "
        "on that page of the pinned file, that the value occurs in the first quote, and that the value sits in the "
        "stated column. A claim that fails is not used.",
        "3. Cases are pairs of claims about the same model and benchmark. Deltas are computed, never typed. The build "
        "fails if a case's text contains a number that is not a value or quoted number of the claims it cites, or a "
        "statistic recomputed from the pinned sources.",
        "4. Each case is assigned to exactly one class:",
        "",
        "| Class | Definition | Counted as a discrepancy |",
        "| :---: | :--- | :---: |",
        f"| A | {catalog['classes']['A']} | yes |",
        f"| B | {catalog['classes']['B']} | yes (protocol effect) |",
        f"| C | {catalog['classes']['C']} | no (context only) |",
        "",
        "## 2. Summary",
        "",
        "| Class | Cases | Median difference (pts) | Range (pts) |",
        "| :---: | :---: | :---: | :---: |",
        f"| A | {s['A']['n']} | {pts(s['A']['median_delta_pts'])} | {pts(s['A']['min_delta_pts'])} to {pts(s['A']['max_delta_pts'])} |",
        f"| B | {s['B']['n']} | {pts(s['B']['median_delta_pts'])} | {pts(s['B']['min_delta_pts'])} to {pts(s['B']['max_delta_pts'])} |",
        f"| C | {s['C']['n']} | not computed | not computed |",
        "",
        f"{sum(1 for c in catalog['cases'] if c['class'] == 'A' and c['delta'] < 3)} of {s['A']['n']} class A "
        "differences are below 3 points, but each is an error or an unexplained change in a published number. Class B "
        "differences are larger: the protocol a headline chooses moves the reported number by several points while "
        "every protocol is disclosed somewhere. No statistic in this repository pools A, B and C.",
        "",
        "![Verified discrepancies by class](assets/synthesis/fig01_verified_discrepancies_by_class.png)",
        "",
        "![Same quantity, two published numbers](assets/synthesis/fig02_same_quantity_two_numbers.png)",
        "",
        "## 3. Cases",
        "",
        "| Case | Class | Model | Benchmark | Higher (source) | Lower (source) | Difference |",
        "| :---: | :---: | :--- | :--- | :--- | :--- | :---: |",
    ]
    for c in catalog["cases"]:
        L.append(f"| [{c['case_id']}](#{c['case_id'].lower()}) | {c['class']} | {c['model']} | {c['benchmark']} | "
                 f"{pts(c['score_high'])} ({c['source_high']}) | {pts(c['score_low'])} ({c['source_low']}) | "
                 f"{pts(c['delta'])} |")
    L.append("")
    for c in catalog["cases"]:
        L += [f"### {c['case_id']}", "",
              f"**{c['model']}, {c['benchmark']}.** Class {c['class']}: {c['kind']}. Difference: {pts(c['delta'])} points.", "",
              c["finding"], "", "Evidence:", ""]
        for cid in [c["high"], c["low"]] + c["support"]:
            L.append(evidence_line(cid, claims, sources))
        L.append("")
    L += ["![Primary-source crops](assets/synthesis/fig03_primary_source_crops.png)", "",
          "## 4. Concordant cross-reports", "",
          "Pairs where two documents report the same number for the same model and benchmark. They are listed to show "
          "that cross-reporting is often exact, which makes the class A cases more notable.", "",
          "| Model | Benchmark | Value | Reported by |", "| :--- | :--- | :---: | :--- |"]
    for p in catalog["concordant"]:
        L.append(f"| {p['model']} | {p['benchmark']} | {pts(p['value'])} | {p['reported_by'][0]}; {p['reported_by'][1]} |")
    L += ["", "## 5. How much can these benchmarks resolve?", "",
          "A benchmark with N independent items cannot distinguish arbitrarily small differences. The table gives, for "
          "each benchmark, the score change from one item and the standard error of a score at an illustrative "
          "accuracy p under a binomial model. The last column is the smallest difference between two independently "
          "scored models that a two-sided unpaired z-test at the 5% level resolves at that p. A paired test on the same "
          "items (McNemar) needs per-item results and is usually tighter, so this column is a conservative bound, not a "
          "property of any model. N is a verified claim.", "",
          "| Benchmark | N | 1 item (pts) | p | SE (pts) | 95% CI half-width (pts) | Unpaired min. difference (pts) |",
          "| :--- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for r in catalog["sampling_resolution"]:
        L.append(f"| {r['benchmark']} | {r['n_items']:,} | {r['one_item_pts']} | {r['p']} | {r['se_pts']} | "
                 f"{r['ci95_half_width_pts']} | {r['mdd_unpaired_pts']} |")
    L += ["", "Two related facts verified in the sources: Anthropic's Claude 3.7 Sonnet score is computed on a 489-task "
          "subset of SWE-bench Verified and OpenAI's o3-mini system card on a 477-task subset, each excluding tasks that "
          "do not run on the vendor's infrastructure (claims `claude37-blog.claude-37-sonnet.swebench-verified.parallel`, "
          "`o3mini-card.o3-mini-tools.swebench-verified`). Headline SWE-bench Verified scores from different vendors are "
          "therefore not always computed on the same tasks.", "",
          "## 6. Source registry", "",
          "| Source id | Title | Pinned address | Bytes | SHA-256 |", "| :--- | :--- | :--- | ---: | :--- |"]
    for sid in sorted(sources):
        x = sources[sid]
        L.append(f"| `{sid}` | {x['title']} | [{x['kind']}]({x['url']}) | {x['bytes']:,} | `{x['sha256'][:16]}` |")
    L.append("")
    return "\n".join(L)


def load():
    catalog = json.loads((ROOT / "data" / "inconsistencies_catalog.json").read_text())
    claims = {c["id"]: c for c in evidence.load_claims()}
    sources = evidence.manifest()
    return catalog, claims, sources
